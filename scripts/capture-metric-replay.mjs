import {createDataCache} from '../lib/data-cache.mjs';
import {qualifyingRepresentatives} from '../corner-geometry.js';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
const year=Number(process.argv[2]||2026),gp=process.argv[3]||'Singapore Grand Prix',round=process.argv[4]||'17';
const subject=process.argv[5]||'team';
const root=resolve('../outputs/ui-cache');await mkdir(root,{recursive:true});
const file=k=>resolve(root,createHash('sha256').update(k).digest('hex')+'.json');
const cache=createDataCache({read:async k=>JSON.parse(await readFile(file(k),'utf8')),write:async(k,v)=>writeFile(file(k),JSON.stringify(v))});
const base=new URLSearchParams({year,gp,round,session:'Q'}),session=(await cache.get('/api/session?'+base)).data;
const Q=(await cache.get('/api/performance?'+new URLSearchParams({year,gp,session:'Q'}))).data;
const rows=qualifyingRepresentatives(session,subject,Q.teams),entries=[],jobs=[...rows];
async function worker(){while(jobs.length){const row=jobs.shift(),q=new URLSearchParams(base);
  for(const [key,value] of Object.entries({driver:row.driver.code,driver_number:row.driver.number,lap:row.lap,lap_time:row.time,lap_start_seconds:row.lap_start_seconds,lap_end_seconds:row.lap_end_seconds}))if(value!=null)q.set(key,String(value));
  if(session.openf1_session_key)q.set('session_key',session.openf1_session_key);
  const payload=(await cache.get('/api/telemetry?'+q,{priority:1})).data;
  const team=Q.teams.find(t=>t.team===row.driver.team),lap=subject==='team'?team.lap:{driver:row.driver.code,number:row.driver.number,lap:row.lap,time:row.time,start:row.lap_start_seconds,end:row.lap_end_seconds,sectors:[row.s1,row.s2,row.s3],phase:row.phase,compound:row.compound};
  const name=subject==='driver'?row.driver.code:team.team;
  entries.push({row,payload,selection:{...lap,team:name,team_name:name,driver_number:lap.number,qualifying_best_time:lap.time,qualifying_best_driver:lap.driver,qualifying_best_lap:lap.lap}});
}}
await Promise.all([worker(),worker(),worker(),worker()]);entries.sort((a,b)=>a.row.time-b.row.time);
const out=resolve('../outputs/'+year+'-'+gp.replaceAll(' ','-')+'-metric-replay'+(subject==='driver'?'-driver':'')+'.json');
await writeFile(out,JSON.stringify({year,gp,round,session,Q,entries}));
console.log(JSON.stringify({out,laps:entries.length,sources:entries.map(e=>[e.row.driver.code,e.payload.source,e.payload.samples.length,Object.keys(e.payload.samples[0])])}));
