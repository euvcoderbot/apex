// What a retired stylesheet (design-system, polish, apple-ui, car-performance, workspace-ui, trace-focus, macos-ui,
// ui-controls, macos-window, hig-system) still contributes: its own text, followed by the appearance rules that
// scripts/migrate-legacy-appearance.mjs moved out of it into skins.css's base block, rebuilt as they were written there
// (selectors unwrapped from :where() and joined back into the original list, inside the original @media/@supports).
// Tests read a file's styling through this, so they keep checking the declarations wherever they now live.
import {readFileSync} from 'node:fs';
import postcss from 'postcss';

const START = '/* ---- Base element styles: generated by scripts/migrate-legacy-appearance.mjs ---- */';
const END = '/* ---- End of base element styles ---- */';

function unwrap(selector) {
  if (!selector.startsWith(':where(')) return selector;
  let depth = 0;
  for (let i = 6; i < selector.length; i++) {
    if (selector[i] === '(') depth++;
    else if (selector[i] === ')' && --depth === 0) {
      const inner = selector.slice(7, i), rest = selector.slice(i + 1);
      return inner === '*' && rest ? rest : inner + rest;
    }
  }
  return selector;
}

/** The base block of skins.css, as text. */
export function baseBlock(skins = readFileSync('skins.css', 'utf8')) {
  const a = skins.indexOf(START), b = skins.indexOf(END);
  return a < 0 || b < 0 ? '' : skins.slice(a, b + END.length);
}
/** skins.css without its generated base block (the hand-written skin rules). */
export function skinRules(skins = readFileSync('skins.css', 'utf8')) {
  const block = baseBlock(skins);
  return block ? skins.replace(block, '') : skins;
}

/** The moved rules of one file, rebuilt as CSS text. */
export function movedFrom(file, skins = readFileSync('skins.css', 'utf8')) {
  const tree = postcss.parse(baseBlock(skins));
  const groups = new Map();
  tree.walkRules(rule => {
    const tag = rule.next()?.type === 'comment' ? rule.next().text.trim() : '';
    const m = tag.match(/^(.+\.css)#(\d+)\.(\d+)$/);
    if (!m || m[1] !== file) return;
    const chain = [];
    for (let p = rule.parent; p && p.type !== 'root'; p = p.parent) chain.unshift(`@${p.name} ${p.params}`);
    const key = m[2];
    if (!groups.has(key)) groups.set(key, {order: Number(key), chain, selectors: [], body: rule.nodes.map(n => n.toString()).join('; ')});
    groups.get(key).selectors[Number(m[3])] = unwrap(rule.selector);
  });
  return [...groups.values()].sort((a, b) => a.order - b.order).map(g => {
    let css = `${g.selectors.filter(Boolean).join(', ')} {\n  ${g.body};\n}`;
    for (const at of [...g.chain].reverse()) css = `${at} {\n${css}\n}`;
    return css;
  }).join('\n');
}

/** A retired file's text with the moved declarations put back: at the end of the rule they came from when it is still there
 * (same selectors, same @media/@supports), else as the rule they were, at the end. */
export function legacySource(file) {
  const own = postcss.parse(readFileSync(file, 'utf8'));
  const norm = s => s.replace(/\s*,\s*/g, ',').replace(/\s+/g, ' ').trim();
  const where = node => { const chain = []; for (let p = node.parent; p && p.type !== 'root'; p = p.parent) chain.unshift(`@${p.name} ${p.params}`); return chain.join('|'); };
  const index = new Map();
  own.walkRules(rule => { const key = `${where(rule)}§${norm(rule.selector)}`; if (!index.has(key)) index.set(key, rule); });
  const moved = postcss.parse(movedFrom(file));
  for (const rule of [...moved.nodes.flatMap(function flat(n) { return n.type === 'rule' ? [n] : (n.nodes || []).flatMap(flat); })]) {
    const target = index.get(`${where(rule)}§${norm(rule.selector)}`);
    if (target) { target.append(...rule.nodes.map(d => d.clone())); rule.remove(); }
  }
  moved.walkAtRules(at => { if (!at.nodes?.length) at.remove(); });
  return `${own.toString()}\n${moved.toString()}\n`;
}
