#!/usr/bin/env node
// Moves every appearance declaration (colour, background, border, shadow, type) out of the retired stylesheets into one block
// at the top of skins.css, keeping today's result exactly:
//  - each moved rule is wrapped in :where(), so it has zero specificity and every existing skins.css rule still beats it,
//    as the skin layer did before;
//  - the moved rules are written in the order the cascade ranked them before (stylesheet layer, then specificity, then
//    source order), so among themselves the same declaration still wins;
//  - every stylesheet above tokens is moved, so no remaining declaration changes rank against a moved one.
// Kept in place: !important declarations (they rank by importance, not position) and rules whose selector Chromium cannot
// parse (they never applied). Layout properties stay where they are.
//   node scripts/migrate-legacy-appearance.mjs [--dry]
import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import postcss from 'postcss';
import {chromium} from 'playwright';
import {UI_STYLES, UI_LAYERS} from '../lib/ui-style-build.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dry = process.argv.includes('--dry');
const FILES = UI_STYLES.map(([file, layer]) => ({file, layer})).filter(({file}) => !['tokens.css', 'skins.css'].includes(file));
const appearance = /^(?:background(?:-.+)?|color|border(?:-.+)?|box-shadow|text-shadow|font(?:-.+)?|letter-spacing|line-height|text-transform|backdrop-filter|filter)$/;
const START = '/* ---- Base element styles: generated by scripts/migrate-legacy-appearance.mjs ---- */';
const END = '/* ---- End of base element styles ---- */';

// Selector specificity [ids, classes/attributes/pseudo-classes, types/pseudo-elements] (Selectors Level 4).
const LEGACY_PSEUDO_ELEMENTS = new Set(['before', 'after', 'first-line', 'first-letter']);
function closing(s, open) { let depth = 0; for (let i = open; i < s.length; i++) { if (s[i] === '(') depth++; else if (s[i] === ')' && --depth === 0) return i; } return s.length - 1; }
function splitTop(s) { const out = []; let depth = 0, cur = ''; for (const ch of s) { if (ch === '(' || ch === '[') depth++; if (ch === ')' || ch === ']') depth--; if (ch === ',' && depth === 0) { out.push(cur); cur = ''; } else cur += ch; } out.push(cur); return out.map(x => x.trim()).filter(Boolean); }
const max = list => list.map(specificity).reduce((m, x) => (cmp(x, m) > 0 ? x : m), [0, 0, 0]);
const add = (a, b) => [a[0] + b[0], a[1] + b[1], a[2] + b[2]];
function cmp(a, b) { return a[0] - b[0] || a[1] - b[1] || a[2] - b[2]; }
function specificity(sel) {
  let r = [0, 0, 0], i = 0;
  const ident = () => { while (i < sel.length && /[\w-]|\\/.test(sel[i])) i += sel[i] === '\\' ? 2 : 1; };
  while (i < sel.length) {
    const ch = sel[i];
    if (ch === '#') { i++; ident(); r = add(r, [1, 0, 0]); }
    else if (ch === '.') { i++; ident(); r = add(r, [0, 1, 0]); }
    else if (ch === '[') { i = sel.indexOf(']', i) + 1 || sel.length; r = add(r, [0, 1, 0]); }
    else if (ch === ':' && sel[i + 1] === ':') { i += 2; ident(); if (sel[i] === '(') i = closing(sel, i) + 1; r = add(r, [0, 0, 1]); }
    else if (ch === ':') {
      i++; const start = i; ident(); const name = sel.slice(start, i).toLowerCase();
      let arg = null; if (sel[i] === '(') { const end = closing(sel, i); arg = sel.slice(i + 1, end); i = end + 1; }
      if (name === 'where') continue;
      if (['is', 'not', 'has', 'matches', '-webkit-any'].includes(name)) r = add(r, max(splitTop(arg || '')));
      else if (['nth-child', 'nth-last-child'].includes(name) && arg && / of /.test(arg)) r = add(add(r, [0, 1, 0]), max(splitTop(arg.split(/ of /)[1])));
      else if (LEGACY_PSEUDO_ELEMENTS.has(name)) r = add(r, [0, 0, 1]);
      else r = add(r, [0, 1, 0]);
    }
    else if (ch === '*') i++;
    else if (/[a-zA-Z_-]/.test(ch)) { ident(); r = add(r, [0, 0, 1]); }
    else i++;
  }
  return r;
}
// :where() cannot hold a pseudo-element: keep it outside.
function zeroSpecificity(sel) {
  const m = sel.match(/(::?(?:before|after|placeholder|marker|selection|backdrop|first-line|first-letter|file-selector-button|-webkit-[\w-]+|-moz-[\w-]+)(?:\([^)]*\))?(?::[\w-]+(?:\([^)]*\))?)*)$/);
  if (m && (m[1].startsWith('::') || LEGACY_PSEUDO_ELEMENTS.has(m[1].slice(1).split(/[:(]/)[0]))) {
    const base = sel.slice(0, -m[1].length).trim();
    return `:where(${base || '*'})${m[1].startsWith('::') ? m[1] : ':' + m[1]}`;
  }
  return `:where(${sel})`;
}

// Which selectors does Chromium accept? A rule with any unsupported selector never applied: leave it alone.
const parsed = [];
for (const [index, {file, layer}] of FILES.entries()) {
  const source = await readFile(path.join(root, file), 'utf8');
  parsed.push({file, layer, rank: UI_LAYERS.indexOf(layer), index, tree: postcss.parse(source, {from: file})});
}
const allSelectors = new Set();
for (const {tree} of parsed) tree.walkRules(rule => postcss.list.comma(rule.selector).forEach(s => allSelectors.add(s)));
const browser = await chromium.launch();
const page = await browser.newPage();
const supported = new Set(await page.evaluate(list => list.filter(s => { try { return CSS.supports(`selector(${s})`); } catch { return false; } }), [...allSelectors]));
await browser.close();

const moved = []; let order = 0, keptImportant = 0, keptInvalid = 0;
for (const {file, rank, index, tree} of parsed) {
  tree.walkRules(rule => {
    order++;
    const chain = [];
    for (let p = rule.parent; p && p.type !== 'root'; p = p.parent) {
      if (p.type === 'rule') return;                                   // nested rules: leave alone
      if (p.type === 'atrule') {
        if (/keyframes|font-face|page/.test(p.name) || (p.name === 'layer')) return;
        chain.unshift(`@${p.name} ${p.params}`);
      }
    }
    const decls = rule.nodes.filter(n => n.type === 'decl' && appearance.test(n.prop));
    if (!decls.length) return;
    const selectors = postcss.list.comma(rule.selector);
    if (selectors.some(s => !supported.has(s))) { keptInvalid += decls.length; return; }
    const move = decls.filter(d => !d.important);
    keptImportant += decls.length - move.length;
    if (!move.length) return;
    const text = move.map(d => `${d.prop}: ${d.value};`).join(' ');
    selectors.forEach((s, k) => moved.push({rank, index, order, k, spec: specificity(s), chain, selector: zeroSpecificity(s), text, file}));
    move.forEach(d => d.remove());
  });
  // Empty rules and blocks left behind go.
  let changed = true;
  while (changed) { changed = false; tree.walk(n => { if ((n.type === 'rule' || (n.type === 'atrule' && n.nodes)) && !n.nodes.some(c => c.type !== 'comment')) { n.remove(); changed = true; } }); }
}
moved.sort((x, y) => x.rank - y.rank || cmp(x.spec, y.spec) || x.index - y.index || x.order - y.order);

// Adjacent rules with the same at-rule context share one block.
let css = '', open = [];
const indent = n => '  '.repeat(n);
for (const m of moved) {
  let common = 0; while (common < open.length && common < m.chain.length && open[common] === m.chain[common]) common++;
  for (let k = open.length; k > common; k--) css += `${indent(k - 1)}}\n`;
  for (let k = common; k < m.chain.length; k++) css += `${indent(k)}${m.chain[k]} {\n`;
  open = m.chain;
  // The source file in a trailing comment (stripped from the shipped, minified stylesheet), so tests and readers can find
  // what each retired file still contributes.
  css += `${indent(open.length)}${m.selector} { ${m.text} } /* ${m.file}#${m.order}.${m.k} */\n`;
}
for (let k = open.length; k > 0; k--) css += `${indent(k - 1)}}\n`;

const header = `${START}
/* The base look of every element, moved here from the retired stylesheets (design-system, polish, apple-ui, car-performance,
   workspace-ui, trace-focus, macos-ui, ui-controls, macos-window, hig-system) with its original precedence: every selector is
   wrapped in :where() (zero specificity), so each rule below this block beats it, and the order reproduces the old cascade.
   Do not add rules here: change the rule that owns a look below, and delete what it makes redundant here. */
`;
const skinsPath = path.join(root, 'skins.css');
let skins = await readFile(skinsPath, 'utf8');
if (skins.includes(START)) skins = skins.slice(0, skins.indexOf(START)) + skins.slice(skins.indexOf(END) + END.length + 1);
// After the opening comment of skins.css, before the tokens.
const firstClose = skins.indexOf('*/') + 2;
skins = `${skins.slice(0, firstClose)}\n\n${header}${css}${END}\n${skins.slice(firstClose)}`;

console.log(JSON.stringify({moved: moved.length, rules: new Set(moved.map(m => `${m.file}:${m.order}`)).size, keptImportant, keptInvalid, bytes: css.length}));
if (!dry) {
  await writeFile(skinsPath, skins);
  for (const {file, tree} of parsed) await writeFile(path.join(root, file), tree.toString());
}
